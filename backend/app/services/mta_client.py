"""Framework-independent subway adapter. Never falls back to sample data."""
from datetime import datetime, timezone
import time

import requests
from google.protobuf.message import DecodeError
from google.transit import gtfs_realtime_pb2 as rt

BASE_URL = 'https://api-endpoint.mta.info/Dataservice/mtagtfsfeeds/'
STATIC_URL = 'https://rrgtfsfeeds.s3.amazonaws.com/gtfs_subway.zip'
ALERTS_URL = BASE_URL + 'camsys%2Fsubway-alerts'
FEED_ROUTES = {
    'gtfs': ('1', '2', '3', '4', '5', '6', '6X', 'GS', '7', '7X'),
    'gtfs-ace': ('A', 'C', 'E', 'H'),
    'gtfs-bdfm': ('B', 'D', 'F', 'FX', 'M', 'FS'),
    'gtfs-g': ('G',), 'gtfs-jz': ('J', 'Z'), 'gtfs-l': ('L',),
    'gtfs-nqrw': ('N', 'Q', 'R', 'W'), 'gtfs-si': ('SI',),
}


class MTAError(RuntimeError):
    """Upstream failure; backend owner should translate to HTTP 503."""


class StaleFeedError(MTAError):
    """Missing, stale, or implausibly future feed timestamp."""


def utc(timestamp):
    return datetime.fromtimestamp(timestamp, timezone.utc).isoformat()


def fetch_feed(feed_url, *, timeout=(3.05, 10), max_age=120, now=None, session=None):
    """Fetch a full GTFS-RT snapshot; timestamps are publisher times, not fetch times."""
    try:
        response = (session or requests).get(feed_url, timeout=timeout)
        response.raise_for_status()
        feed = rt.FeedMessage()
        feed.ParseFromString(response.content)
    except (requests.RequestException, DecodeError) as exc:
        raise MTAError('MTA request failed or returned invalid protobuf') from exc
    if not feed.IsInitialized() or feed.header.incrementality != rt.FeedHeader.FULL_DATASET:
        raise MTAError('Expected a complete GTFS-RT snapshot')
    validate_freshness(feed, max_age=max_age, now=now)
    return feed


def validate_freshness(feed, *, max_age=120, now=None):
    now = time.time() if now is None else now
    timestamp = feed.header.timestamp
    if not timestamp or now - timestamp > max_age or timestamp - now > 60:
        raise StaleFeedError('MTA feed timestamp is missing, stale, or in the future')


def normalize_arrivals(feeds, station_id, catalog, *, now=None):
    """catalog is generated by static_gtfs.build_catalog; feeds must be validated."""
    now = time.time() if now is None else now
    if station_id not in {s['id'] for s in catalog['stations']}:
        raise ValueError('Unknown GTFS parent station')
    if not feeds:
        raise MTAError('No arrival feeds supplied')
    results = {}
    for feed in feeds:
        for entity in feed.entity:
            if entity.is_deleted or not entity.HasField('trip_update'):
                continue
            update = entity.trip_update
            trip = update.trip
            # DELETED=7 is not named in older supported protobuf bindings.
            if trip.schedule_relationship in (rt.TripDescriptor.CANCELED, 7):
                continue
            for stop in update.stop_time_update:
                platform = catalog['stops'].get(stop.stop_id)
                if not platform or platform['station_id'] != station_id:
                    continue
                if stop.schedule_relationship in (rt.TripUpdate.StopTimeUpdate.SKIPPED,
                                                   rt.TripUpdate.StopTimeUpdate.NO_DATA):
                    continue
                timestamp = stop.arrival.time or stop.departure.time
                if timestamp < now:
                    continue
                # Use the reported last stop only: static trip IDs often differ from realtime.
                terminal = catalog['stops'].get(update.stop_time_update[-1].stop_id, {})
                destination = terminal.get('name', 'Destination unavailable')
                direction = platform['direction']
                key = (trip.trip_id or entity.id, trip.start_date, stop.stop_id, stop.stop_sequence)
                results[key] = {
                    'id': ':'.join(map(str, key)), 'route_id': trip.route_id,
                    'destination': destination, 'direction': direction,
                    'arrival_time': utc(timestamp),
                }
    return {'station_id': station_id, 'source': 'mta',
            'updated_at': utc(min(f.header.timestamp for f in feeds)),
            'arrivals': sorted(results.values(), key=lambda a: (a['arrival_time'], a['id']))}


def translated_text(value):
    texts = value.translation
    return next((t.text for t in texts if t.language.lower().split('-')[0] == 'en'),
                texts[0].text if texts else '')


def normalize_alerts(feed, route_id=None, *, now=None):
    now = time.time() if now is None else now
    alerts = []
    for entity in feed.entity:
        if entity.is_deleted or not entity.HasField('alert'):
            continue
        alert = entity.alert
        if alert.active_period and not any(
                (not p.HasField('start') or p.start <= now) and
                (not p.HasField('end') or now < p.end) for p in alert.active_period):
            continue
        routes = sorted({s.route_id for s in alert.informed_entity if s.route_id})
        # Empty route_ids includes network-wide and stop-only alerts; don't hide them.
        if route_id and routes and route_id not in routes:
            continue
        alerts.append({'id': entity.id, 'header': translated_text(alert.header_text),
                       'description': translated_text(alert.description_text), 'route_ids': routes})
    return {'source': 'mta', 'alerts': sorted(alerts, key=lambda a: a['id'])}


class MTAClient:
    def __init__(self, catalog, *, timeout=(3.05, 10), max_age=120, alerts_max_age=600, session=None):
        self.catalog = catalog
        self.timeout = timeout
        self.max_age = max_age
        self.alerts_max_age = alerts_max_age
        self.session = session

    def arrivals(self, station_id):
        station = next((s for s in self.catalog['stations'] if s['id'] == station_id), None)
        if station is None:
            raise ValueError('Unknown GTFS parent station')
        routes = set(station['routes'])
        covered = {r for group in FEED_ROUTES.values() for r in group}
        if routes - covered or not routes:
            raise MTAError('Station has unsupported or missing route-to-feed mappings')
        feeds = [fetch_feed(BASE_URL + 'nyct%2F' + name, timeout=self.timeout,
                            max_age=self.max_age, session=self.session)
                 for name, group in FEED_ROUTES.items() if routes.intersection(group)]
        return normalize_arrivals(feeds, station_id, self.catalog)

    def alerts(self, route_id=None):
        feed = fetch_feed(ALERTS_URL, timeout=self.timeout, max_age=self.alerts_max_age,
                          session=self.session)
        return normalize_alerts(feed, route_id)
